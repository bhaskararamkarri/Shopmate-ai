/**
 * ShopMate AI — Shared Type Definitions
 *
 * These types will be fleshed out during Phases 3–5 (catalog, AI, PayPal).
 * For Phase 1 they exist to define the contracts between modules.
 */

/** Explicit product source identifier: live Channel3 feed vs local demo catalog. */
export type ProductSource = 'channel3' | 'demo';

/** A verified product record from the catalog (never fabricated). */
export interface Product {
  /** Unique product identifier from the catalog source. */
  id: string;
  name: string;
  description: string;
  /** Price in minor... in decimal currency units (e.g., 249.99 USD). */
  price: number;
  currency: string;
  /** 'unknown' when the source publishes no stock data — never guessed. */
  availability: 'in_stock' | 'out_of_stock' | 'limited' | 'unknown';
  images: string[];
  ratings: number;
  reviews: number;
  category: string;
  brand: string;
  specs: Record<string, string>;
  sku?: string;
  /** Explicit catalog source: 'channel3' = live feed, 'demo' = local mock. */
  source: ProductSource;
  /** Live merchant domain (e.g. "nike.com") for channel3 records. */
  merchant?: string;
  /** Fresh offer/buy URL from the live feed; short-lived by Channel3 design. */
  buyUrl?: string;
  /** Original price before a discount, when the live offer is on sale. */
  compareAtPrice?: number;
  /** True when this record comes from the local demo catalog. Kept in sync with `source`. */
  demo?: boolean;
  /** Drawn iconography for demo records; real records rely on `images`. */
  visual?: ProductVisual;
  /** Comparable attributes powering advantage/trade-off notes. */
  attributes?: ProductAttribute[];
}

/** Visual key for the code-drawn product tiles used across the demo UI. */
export type ProductGlyph =
  | 'headphones'
  | 'earbuds'
  | 'speaker'
  | 'keyboard'
  | 'mouse'
  | 'lamp'
  | 'watch'
  | 'sleep-ring'
  | 'camera'
  | 'action-cam';

/** Washed-out pastel surface tints for demo product tiles. */
export type ProductTint = 'blue' | 'red' | 'green' | 'amber';

/** Drawn tile appearance for demo products (inverted to real imagery once the live catalog lands). */
export interface ProductVisual {
  glyph: ProductGlyph;
  tint: ProductTint;
}

/** A comparable product attribute, with the direction that counts as better when known. */
export interface ProductAttribute {
  label: string;
  value: string;
  /** 'higher' or 'lower' — the direction that reads as an advantage. Optional. */
  better?: 'higher' | 'lower';
}

/** An item placed in the user's cart. */
export interface CartItem {
  product: Product;
  quantity: number;
}

/** A placed PayPal order (server-verified). */
export interface Order {
  id: string;
  items: CartItem[];
  /** Server-calculated total. Never computed client-side. */
  total: number;
  currency: string;
  status: 'created' | 'approved' | 'captured' | 'failed';
  createdAt: string;
}

/** How an assistant reply was produced, for transparent provenance in the UI. */
export interface AgentMeta {
  /** 'ai' = model-driven turn; 'keyword_fallback' = deterministic no-AI path. */
  mode: 'ai' | 'keyword_fallback';
  /** Model id when mode is 'ai' (e.g. "gemini-3.8-flash"). */
  model?: string;
  /** Agent tools that ran during the turn, in call order. */
  toolsUsed: string[];
  /** Where the product data came from — demo degradation is always visible. */
  catalog: { source: 'channel3' | 'demo'; fallback?: string };
}

/** A single message in the AI shopping conversation. */
export interface ChatMessage {
  id: string;
  role: 'user' | 'assistant' | 'system';
  content: string;
  createdAt: string;
  /** Products referenced by the assistant (must come from verified catalog). */
  productRefs?: string[];
  /** Resolved product records attached to the reply (live or demo). */
  products?: Product[];
  /** Structured shopping intent after this turn (assistant messages). */
  intent?: ShoppingIntentSummary;
  /** Evidenced product recommendation insights from the decision engine. */
  recommendations?: ProductRecommendationInsight[];
  /** Provenance metadata for assistant replies produced by the agent. */
  agentMeta?: AgentMeta;
}

/**
 * Transparent recommendation insight generated by the Decision Engine.
 * All points are grounded in catalog facts or explicit user requirements.
 */
export interface ProductRecommendationInsight {
  productId: string;
  badge?: "Best Overall" | "Best Value" | "Best Fit";
  whyItMatches: string;
  requirementsSatisfied: string[];
  /** Explicitly documented mandatory requirements that this product failed (if any). */
  failedRequirements?: string[];
  missingOrUnverified: string[];
  tradeOffs: string[];
  whoShouldChoose: string;
}

/**
 * Intent summary persisted with a message. Structural subset of the agent's
 * ShoppingIntent (kept loose here so the UI never imports agent internals).
 */
export interface ShoppingIntentSummary {
  category?: string;
  productCategory?: string;
  query?: string;
  budget?: { amount: number; currency: string } | null;
  budgetMin?: number;
  budgetMax?: number;
  currency?: string;
  intendedUse?: string;
  requiredFeatures?: string[];
  preferredFeatures?: string[];
  excludedFeatures?: string[];
  brands: string[];
  requiredSpecs: Record<string, string>;
  priorities: string[];
  constraints?: string[];
  clarifications: string[];
}